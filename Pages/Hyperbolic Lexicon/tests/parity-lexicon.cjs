// ------------------------------------------------------------------ the strict UTF-8 decoder
// An independent Table 3-7 scanner (the reference's tests/test_normalise.py table_3_7_first_bad, written again).
function table37FirstBad(b) {
    let i = 0;
    while (i < b.length) {
        const c = b[i];
        if (c < 0x80) { i++; continue; }
        let need;
        if (c >= 0xC2 && c <= 0xDF) need = [[0x80, 0xBF]];
        else if (c === 0xE0) need = [[0xA0, 0xBF], [0x80, 0xBF]];
        else if ((c >= 0xE1 && c <= 0xEC) || c === 0xEE || c === 0xEF) need = [[0x80, 0xBF], [0x80, 0xBF]];
        else if (c === 0xED) need = [[0x80, 0x9F], [0x80, 0xBF]];
        else if (c === 0xF0) need = [[0x90, 0xBF], [0x80, 0xBF], [0x80, 0xBF]];
        else if (c >= 0xF1 && c <= 0xF3) need = [[0x80, 0xBF], [0x80, 0xBF], [0x80, 0xBF]];
        else if (c === 0xF4) need = [[0x80, 0x8F], [0x80, 0xBF], [0x80, 0xBF]];
        else return i;
        for (let k = 0; k < need.length; k++) if (i + 1 + k >= b.length || b[i + 1 + k] < need[k][0] || b[i + 1 + k] > need[k][1]) return i;
        i += 1 + need.length;
    }
    return null;
}
