const chainLabel = (w, j) => (w.startsWith('#') ? `comment ${j + 1}` : `${j + 1}: ${w.split(' ').slice(0, 3).join(' ')}`);
function chainLines(want, got) {
    const cline = (label, ok, detail = '') => ({ section: 'chain', label, ok: !!ok, detail });
    if (typeof want !== 'string') return [{ section: 'chain', label: 'file', ok: false, skip: true, detail: 'reference/traces/chain_v1.txt is absent (reference/traces_chain.py writes it)' }];
    const w = want.split('\n'), out = [cline('file', w[w.length - 1] === '' && (w.length < 2 || w[w.length - 2] !== ''), 'ends with one LF')];
    w.pop();
    w.forEach((x, j) => {
        if (j >= got.lines.length) { out.push(got.complete ? cline(chainLabel(x, j), false, 'the core wrote no such line') : { section: 'chain', label: chainLabel(x, j), ok: false, skip: true, detail: 'needs WordNet' }); return; }
        const ok = got.lines[j] === x;
        out.push(cline(chainLabel(x, j), ok, ok ? (x.length > 70 ? x.slice(0, 70) + '…' : x) : `trace "${x.slice(0, 120)}" vs core "${got.lines[j].slice(0, 120)}"`));
    });
    if (got.lines.length > w.length) out.push(cline('extra lines', false, `the core wrote ${got.lines.length - w.length} lines more than the trace`));
    return out;
}
