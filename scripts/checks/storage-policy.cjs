#!/usr/bin/env node
// Browser storage policy for the whole site (every page and script tracked in the repository).
//   node scripts/checks/storage-policy.cjs
// Fails (exit 1) when
//   - any code clears a whole storage area (localStorage.clear() or sessionStorage.clear()): the site shares its
//     origin with other apps, so each page removes only its own keys;
//   - a localStorage/sessionStorage key is outside the allowed prefixes, unless it is one of the legacy keys below;
//     this covers getItem/setItem/removeItem, localStorage["key"] and localStorage.key used as a property (read,
//     written or deleted);
//   - a key passed to getItem/setItem/removeItem cannot be worked out from the source (a literal, a template with a
//     literal start, a constant, or a wrapper function called with one of those);
//   - moveLegacyKeys() (assets/js/storage-keys.js) is called with anything but a literal storage area and a list of
//     string literals that are all listed in MOVED below;
//   - a storage area is reached in a way this check cannot follow: passed to a function, put in an array or object,
//     returned, looked up with window[...] / globalThis[...] / self[...], or through Storage.prototype. Reviewed
//     files that do this on purpose are listed in REVIEWED below, pinned by content.
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '../..');
const PREFIXES = ['ebayednoob-', 'engram-minds-eye/', 'hyperbolic-lexicon/'];
// Keys outside the prefixes that are allowed, each with the reason it stays as it is.
const LEGACY = {
    'glh-theme': 'Geometric Calculator light/dark preference. The four pages that use it are generated by '
        + 'scripts/geometric-build/build.py and pinned byte for byte by tests/rebuild-identical.sh; rename it '
        + 'in the templates (reading the old key once) the next time the build changes on purpose.',
    'engram_mind_eye_v1': "Owl Academy's own key. It appears only in the loader snippet that Engram's Mind's Eye "
        + 'copies for the visitor to run in Owl Academy (and in the preview of that snippet); this site never '
        + 'writes it from its own pages.',
};
// Library-owned keys outside the prefixes (a template start), each with the reason this site touches it.
const FOREIGN_PREFIXES = {
    'firebase:authUser:': "Firebase Auth's own key for a saved sign-in. assets/js/firebase.js and index.html read it "
        + 'once to move a Google sign-in that an earlier version saved in localStorage into the tab\'s sessionStorage, '
        + "and remove it from localStorage; the learning hubs' anonymous sign-ins are left alone.",
};
// Old unprefixed keys of this site that moveLegacyKeys() may move to "ebayednoob-" + name ("*" = keys starting with
// the text before it). Each is this site's own; none may name another app's key.
const MOVED = {
    'browser-layout:*': 'Research hub grid/list choice per collection (assets/js/collection-browser.js).',
    'research-live-scan': 'Research hub live scan result in sessionStorage (Pages/Research/research.js).',
    'studio-mode': 'Studio editor mode (control-panel/studio.js).',
    'studio-backup:*': 'Studio unsaved-draft backups (control-panel/studio.js).',
};
// Files that reach a storage area in a way the rules above cannot follow, reviewed and pinned by sha256: a change to
// the file fails this check until it is reviewed again and the hash updated.
const REVIEWED = {
    'assets/js/storage-keys.js': {
        sha256: 'ffc9c0ce59f4031916f0e75598e31208de77a54d6257fefa99f8a34e338c071d',
        why: 'moveLegacyKeys(area, names): reads the listed old keys and writes them to "ebayednoob-" + name. Its calls '
            + 'are checked at the call sites (MOVED).',
    },
    'tests/site/github-store.test.cjs': {
        why: 'Unit test: installs fake storage objects on globalThis before loading the modules under test.',
    },
};
const SELF = 'scripts/checks/';
const EXT = /\.(html?|m?js|cjs)$/i;

function listFiles() {
    const out = execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], { cwd: ROOT, maxBuffer: 1 << 26 });
    return out.toString('utf8').split('\0').filter((f) => f && EXT.test(f) && !f.startsWith(SELF) && fs.existsSync(path.join(ROOT, f)));
}

const lineOf = (src, i) => src.slice(0, i).split('\n').length;
const STORAGE = '(?:\\b(?:window|globalThis|self)\\s*\\.\\s*)?\\b(?:localStorage|sessionStorage)\\b';

// Reads a JS expression starting at i (a string literal, a template literal, a call or a name); returns its text.
function readArg(src, i) {
    while (/\s/.test(src[i] || '')) i++;
    const start = i;
    const q = src[i];
    if (q === '"' || q === "'" || q === '`') {
        i++;
        let depth = 0;
        while (i < src.length) {
            const c = src[i];
            if (c === '\\') { i += 2; continue; }
            if (q === '`' && c === '$' && src[i + 1] === '{') { depth++; i += 2; continue; }
            if (q === '`' && c === '}' && depth > 0) { depth--; i++; continue; }
            if (c === q && depth === 0) return src.slice(start, i + 1);
            i++;
        }
        return src.slice(start);
    }
    const m = /^[A-Za-z_$][\w$]*(?:\s*\.\s*[A-Za-z_$][\w$]*)*(\s*\(\s*\))?/.exec(src.slice(i));
    return m ? m[0] : '';
}

// Resolve an argument to { key } (exact), { prefix } (template with a literal start), { param } or {}.
function resolve(src, expr, at, depth = 0) {
    expr = expr.trim();
    if (depth > 4 || !expr) return {};
    if (/^(['"]).*\1$/s.test(expr)) return { key: expr.slice(1, -1) };
    if (expr[0] === '`') {
        const head = expr.slice(1, expr.indexOf('${') === -1 ? -1 : expr.indexOf('${'));
        return expr.includes('${') ? { prefix: head } : { key: head };
    }
    const call = /^([A-Za-z_$][\w$]*)\s*\(\s*\)$/.exec(expr);
    if (call) {
        const def = new RegExp(`(?:\\b(?:const|let|var)\\s+|,\\s*)${call[1]}\\s*=\\s*\\([^)]*\\)\\s*=>\\s*`).exec(src)
            || new RegExp(`\\bfunction\\s+${call[1]}\\s*\\([^)]*\\)\\s*\\{\\s*return\\s+`).exec(src);
        return def ? resolve(src, readArg(src, def.index + def[0].length), at, depth + 1) : {};
    }
    if (/^[A-Za-z_$][\w$]*$/.test(expr)) {
        // The nearest binding before the use: a constant/variable, or a parameter of a wrapper function.
        const def = new RegExp(`(?:\\b(?:const|let|var)\\s+|,\\s*)${expr}\\s*=\\s*`, 'g');
        let m, before = null, any = null;
        while ((m = def.exec(src))) {
            if (!any) any = m;
            if (m.index < at) before = m;
        }
        const fnRe = /\bfunction\s+([A-Za-z_$][\w$]*)\s*\(([^)]*)\)|\b(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*\(([^)]*)\)\s*=>/g;
        let f, wrapper = null;
        while ((f = fnRe.exec(src)) && f.index < at) {
            const params = (f[2] ?? f[4] ?? '').split(',').map((p) => p.trim().split('=')[0].trim());
            if (params.includes(expr)) wrapper = { name: f[1] || f[3], index: f.index };
        }
        if (wrapper && (!before || wrapper.index > before.index)) return { param: wrapper.name };
        const use = before || any;
        if (use) return resolve(src, readArg(src, use.index + use[0].length), at, depth + 1);
    }
    return {};
}

const allowed = (key) => PREFIXES.some((p) => key.startsWith(p));
const foreign = (key) => Object.keys(FOREIGN_PREFIXES).some((p) => key.startsWith(p));

// The code of a file with comments and the text of string and template literals blanked (offsets kept); for HTML,
// only the inline <script> blocks. Used by the rules about how a storage area is reached.
function codeOnly(file, src) {
    const out = src.split('').map((c) => (c === '\n' ? '\n' : ' '));
    const ranges = /\.html?$/i.test(file)
        ? [...src.matchAll(/<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)].map((m) => [m.index + m[0].indexOf('>') + 1, m.index + m[0].indexOf('>') + 1 + m[1].length])
        : [[0, src.length]];
    for (const [from, to] of ranges) {
        let i = from;
        const stack = []; // template nesting: brace depth at each ${
        let inTpl = false;
        let depth = 0;
        while (i < to) {
            const c = src[i];
            if (inTpl) {
                if (c === '\\') { i += 2; continue; }
                if (c === '`') { inTpl = false; i++; continue; }
                if (c === '$' && src[i + 1] === '{') { stack.push(depth); depth = 0; inTpl = false; i += 2; continue; }
                i++;
                continue;
            }
            if (c === '/' && src[i + 1] === '/') { while (i < to && src[i] !== '\n') i++; continue; }
            if (c === '/' && src[i + 1] === '*') { const e = src.indexOf('*/', i + 2); i = e < 0 ? to : e + 2; continue; }
            if (c === '"' || c === "'") { i++; while (i < to && src[i] !== c && src[i] !== '\n') i += src[i] === '\\' ? 2 : 1; i++; continue; }
            if (c === '`') { inTpl = true; i++; continue; }
            if (c === '{') depth++;
            if (c === '}') { if (depth === 0 && stack.length) { depth = stack.pop(); inTpl = true; i++; continue; } depth--; }
            out[i] = c;
            i++;
        }
    }
    return out.join('');
}

// The string literals of an array literal text such as `["a", 'b*']`, or null when it holds anything else.
function stringList(text) {
    const m = /^\[\s*([\s\S]*?)\s*,?\s*\]$/.exec(text.trim());
    if (!m) return null;
    if (!m[1]) return [];
    const items = m[1].split(',').map((x) => x.trim());
    return items.every((x) => /^(['"])[^'"\\]*\1$/.test(x)) ? items.map((x) => x.slice(1, -1)) : null;
}

const violations = [];
const keys = new Map(); // key or prefix* -> Set of files
const note = (k, file) => { if (!keys.has(k)) keys.set(k, new Set()); keys.get(k).add(file); };

function checkKey(file, src, line, r, how) {
    if (r.key !== undefined) {
        note(r.key, file);
        if (!allowed(r.key) && !LEGACY[r.key]) violations.push(`${file}:${line}: key "${r.key}" is outside ${PREFIXES.join(', ')} (${how})`);
    } else if (r.prefix !== undefined) {
        note(`${r.prefix}*`, file);
        if (!allowed(r.prefix) && !(foreign(r.prefix) && r.prefix.length > 0)) violations.push(`${file}:${line}: key template starting "${r.prefix}" is outside ${PREFIXES.join(', ')} (${how})`);
    } else {
        violations.push(`${file}:${line}: cannot work out the storage key (${how})`);
    }
}

// MOVED itself: every name is this site's own (not another app's prefix, not a legacy key of another app).
for (const name of Object.keys(MOVED)) {
    const base = name.endsWith('*') ? name.slice(0, -1) : name;
    if (base.length < 4 || PREFIXES.some((p) => base.startsWith(p) || p.startsWith(base)) || LEGACY[base] || foreign(base)) {
        violations.push(`scripts/checks/storage-policy.cjs: MOVED name "${name}" could reach keys that are not this site's old keys`);
    }
}

const files = listFiles();
let calls = 0;
let moves = 0;
for (const file of files) {
    const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
    const reviewed = REVIEWED[file];
    if (reviewed?.sha256) {
        const sha = crypto.createHash('sha256').update(src).digest('hex');
        if (sha !== reviewed.sha256) violations.push(`${file}: changed since it was reviewed (sha256 ${sha}); review it again and update REVIEWED in scripts/checks/storage-policy.cjs`);
    }

    // moveLegacyKeys("localStorage" | "sessionStorage", ["name", "prefix*", ...]) with names from MOVED.
    for (const m of src.matchAll(/\bmoveLegacyKeys\s*\(/g)) {
        if (reviewed) break; // the definition, or a test of it
        if (/\bfunction\s+$/.test(src.slice(Math.max(0, m.index - 9), m.index))) continue; // the definition
        let d = 0, end = m.index + m[0].length;
        for (; end < src.length; end++) {
            const c = src[end];
            if (c === '(' || c === '[' || c === '{') d++;
            else if (c === ')' || c === ']' || c === '}') { if (d === 0) break; d--; }
        }
        const args = src.slice(m.index + m[0].length, end);
        const am = /^\s*(['"])(localStorage|sessionStorage)\1\s*,\s*([\s\S]*?)\s*$/.exec(args);
        const names = am ? stringList(am[3]) : null;
        const line = lineOf(src, m.index);
        moves++;
        if (!names) { violations.push(`${file}:${line}: moveLegacyKeys() needs a literal storage area and a list of string literals`); continue; }
        for (const n of names) {
            if (!MOVED[n]) violations.push(`${file}:${line}: moveLegacyKeys() name "${n}" is not listed in MOVED`);
            else note(`ebayednoob-${n}`, file);
        }
    }

    if (!/Storage/.test(src)) continue;
    const code = codeOnly(file, src);
    if (!reviewed) {
        for (const m of code.matchAll(/\bStorage\s*\.\s*prototype\b/g)) violations.push(`${file}:${lineOf(src, m.index)}: uses Storage.prototype; call the storage area's own methods with a prefixed key`);
        for (const m of code.matchAll(/\b(?:window|globalThis|self)\s*\[/g)) violations.push(`${file}:${lineOf(src, m.index)}: looks up a global by a computed name in a file that uses storage; name the storage area directly`);
        // A storage area used as a value: passed, stored, returned, or put in an array/object.
        for (const m of code.matchAll(/(?<![\w$.])(?:(?:window|globalThis|self)\s*\.\s*)?(localStorage|sessionStorage)\b(?!\s*(?:\?\.|\.|\[))/g)) {
            const before = code.slice(Math.max(0, m.index - 80), m.index);
            const after = code.slice(m.index + m[0].length, m.index + m[0].length + 40);
            if (/\btypeof\s*$/.test(before)) continue; // typeof localStorage
            if (/^\s*(?:===?|!==?)\s*(?:undefined|null)\b/.test(after) || /(?:undefined|null)\s*(?:===?|!==?)\s*$/.test(before)) continue; // presence test
            if (/^\s*in\b/.test(after)) continue;
            if (/\b(?:const|let|var)\s+[A-Za-z_$][\w$]*\s*=[^;\n]*$/.test(before)) continue; // an alias, followed below
            violations.push(`${file}:${lineOf(src, m.index)}: ${m[1]} is used as a value (passed, stored or returned), so this check cannot follow its keys; call its methods here with a prefixed key`);
        }
    }
    if (!/localStorage|sessionStorage/.test(src)) continue;
    // Names bound to a storage area, e.g. `const ls = typeof localStorage !== 'undefined' ? localStorage : null`.
    const aliases = [];
    for (const m of src.matchAll(/\b(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*[^;\n]*\b(?:localStorage|sessionStorage)\b(?!\s*(?:\?\.|\.|\[))[^;\n]*/g)) aliases.push(m[1]);
    const recv = aliases.length ? `(?:${STORAGE}|\\b(?:${aliases.join('|')})\\b)` : STORAGE;

    for (const m of src.matchAll(new RegExp(`${recv}\\s*\\.\\s*clear\\s*\\(`, 'g'))) {
        violations.push(`${file}:${lineOf(src, m.index)}: clears a whole storage area; remove only this site's own keys`);
    }
    for (const m of src.matchAll(new RegExp(`${recv}\\s*\\[\\s*(['"\`])`, 'g'))) {
        const at = m.index + m[0].length - 1;
        calls++;
        checkKey(file, src, lineOf(src, m.index), resolve(src, readArg(src, at), m.index), 'property access');
    }
    // localStorage.someKey used as a property (read, written or deleted): the property name is the key.
    for (const m of src.matchAll(new RegExp(`${recv}\\s*\\.\\s*(?!(?:getItem|setItem|removeItem|key|length|clear)\\b)([A-Za-z_$][\\w$]*)`, 'g'))) {
        if (reviewed) continue;
        if (code[m.index] === ' ') continue; // inside a comment or string
        calls++;
        checkKey(file, src, lineOf(src, m.index), { key: m[1] }, 'property');
    }
    for (const m of src.matchAll(new RegExp(`${recv}\\s*\\.\\s*(getItem|setItem|removeItem)\\s*\\(`, 'g'))) {
        if (reviewed) continue; // a reviewed wrapper: its calls are checked at the call sites
        calls++;
        const at = m.index + m[0].length;
        const line = lineOf(src, m.index);
        const r = resolve(src, readArg(src, at), m.index);
        if (r.param) {
            // A wrapper such as `function store(key, value) { ... localStorage.getItem(key) ... }`: check its callers.
            const sites = [...src.matchAll(new RegExp(`\\b${r.param}\\s*\\(`, 'g'))]
                .filter((c) => !/function\s+$|=\s*$/.test(src.slice(Math.max(0, c.index - 12), c.index)) && !/\bfunction\s+$/.test(src.slice(Math.max(0, c.index - 9), c.index)));
            for (const c of sites) {
                const before = src.slice(Math.max(0, c.index - 40), c.index);
                if (new RegExp(`(?:function\\s+|(?:const|let|var)\\s+)$`).test(before)) continue; // the definition
                const arg = readArg(src, c.index + c[0].length);
                checkKey(file, src, lineOf(src, c.index), resolve(src, arg, c.index), `through ${r.param}()`);
            }
            continue;
        }
        checkKey(file, src, line, r, m[1]);
    }
}

console.log(`storage policy: ${files.length} files, ${calls} storage calls, ${moves} moveLegacyKeys calls; allowed prefixes ${PREFIXES.join(', ')}`);
for (const [k, fs_] of [...keys].sort()) {
    const tag = LEGACY[k] ? '  (legacy)' : '';
    console.log(`  ${k}${tag}: ${[...fs_].length} file(s)`);
}
for (const [k, why] of Object.entries(LEGACY)) console.log(`legacy key "${k}": ${why}`);
for (const [k, why] of Object.entries(FOREIGN_PREFIXES)) console.log(`library key "${k}*": ${why}`);
for (const [k, why] of Object.entries(MOVED)) console.log(`moved to "ebayednoob-${k}": ${why}`);
for (const [f, r] of Object.entries(REVIEWED)) console.log(`reviewed file ${f}: ${r.why}`);
if (violations.length) {
    console.log(`\nFAIL: ${violations.length} problem(s)`);
    for (const v of violations) console.log(`  ${v}`);
    process.exit(1);
}
console.log('ok: no storage area is cleared and every key is prefixed or a listed legacy key');
