# fixed <i> <x as 16 hex digits> <x.toFixed(12)> <x.toFixed(4)> <String(x)>: x from the same Rng after the hypot cases
# synth <seed> <draws> <bytes> <code points> <two-byte code points> <chunks> <chunks with a 0x80 crystal byte>
