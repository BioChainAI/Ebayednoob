def dhex(x):
    return struct.pack('>d', x).hex()


def lst(xs):
    xs = [str(x) for x in xs]
    return ','.join(xs) if xs else '-'


def tf(b):
    return 'true' if b else 'false'


def codec_cases():
    r5 = Rng(SEED_CODEC)
    r6 = Rng(SEED_CODEC + 1)
    return [('C0', b'a'), ('C1', b'Hello, world!'), ('C2', bytes([75, 0, 7])), ('C3', bytes(range(256))),
            ('C4', bytes(720)), ('C5', bytes(r5.below(256) for _ in range(720))),
            ('C6', bytes(97 + r6.below(4) for _ in range(720))), ('C7', ('é' * 150).encode('utf-8'))]


def trace_words():
    out = []
    for r in range(12):
        g = Rng(SEED_ADDR + r)
        n = 1 + g.below(12)
        w = [g.below(6)]
        while len(w) < n:
            w.append(children(w)[g.below(5)])
        out.append(tuple(w))
    return out


TRACE_TOKENS = ['[PAD]', '[UNK]', 'the', '##ing', 'cat', '##s', '|', 'é', '中', 'run', '42', '...']


def build(wn):
    out = [HEADER.rstrip('\n')]
    say = out.append
    v0 = WP.load_v0()

    # ---- codec
    for name, b in codec_cases():
        res = C.encode_chunk(b)
        rtxt = res if len(res) <= 128 else 'sha256:' + hashlib.sha256(res.encode()).hexdigest()
        say(f'codec {name} {len(b)} {C.crystallize(b)} {C.kernel_crystallize(b)} {tf(C.crystal_has_80(b))} '
            f'{C.quat_hex(C.crystal_quat(b))} {C.leaf_hash(0, b)} {len(res)} {rtxt}')
        say(f'decode {name} {tf(C.decode_chunk(res, len(b)) == list(b))}')
    for name, b in codec_cases():
        if name in ('C1', 'C6'):
            fl = C.silent_flips(C.encode_chunk(b), b)
            say(f'silent {name} {len(fl)} ' + lst(f"{x['i']}:{x['bit']}:{x['kind']}" for x in fl[:8]))

    # ---- V8's Math.hypot and toFixed
    g = Rng(SEED_HYPOT)

    def draw():
        x = (2 * g.random() - 1) * SCALES[g.below(13)]
        if g.below(8) == 0:
            x = 0.0
        if g.below(16) == 0:
            x = -0.0 if x == 0 else x
        return x
    for i in range(40):
        a = [draw() for _ in range(4)]
        say(f'hypot {i} ' + ' '.join(dhex(x) for x in a) + f' {dhex(C.v8_hypot(a))} {C.quat_hex(C.qn(a))}')
    for i in range(40):
        x = draw()
        say(f'fixed {i} {dhex(x)} {C.js_to_fixed(x, 12)} {C.js_to_fixed(x, 4)} {C.js_number(x)}')

    # ---- shards
    shards = []
    for i in range(3):
        text, draws = C.synth_shard(SEED_SYNTH + i)
        data = text.encode('utf-8')
        two, cps = C.two_byte_share(text)
        chunks = [data[k:k + C.CHUNK] for k in range(0, len(data), C.CHUNK)]
        say(f'synth {SEED_SYNTH + i} {draws} {len(data)} {cps} {two} {len(chunks)} '
            f'{sum(C.crystal_has_80(c) for c in chunks)} {hashlib.sha256(data).hexdigest()}')
        shards.append((f'S{i}', text, R.SPDX_CC0, R.source_url_sha_synth(SEED_SYNTH, i)))
    for k, text in enumerate(C.gloss_shards(wn, 'verb')[:2]):
        shards.append((f'V{k}', text, R.SPDX_WORDNET, R.source_url_sha_c0()))
    for name, text, _, _ in shards:
        say(f'shard {name} {len(text.encode())} {hashlib.sha256(text.encode()).hexdigest()}')

    recs = {}
    for name, text, _, _ in shards:
        for mode in ('off', 'on'):
            rec = C.grow(text, engrams=mode == 'on')
            recs[name, mode] = rec
            for k, v in rec.items():
                if k in ('stream', 'engramStream'):
                    val = f'{len(v)} {hashlib.sha256(v.encode()).hexdigest()}'
                elif k == 'leafHashes':
                    val = f'{len(v)} {hashlib.sha256(C.js_json(v).encode()).hexdigest()}'
                elif k == 'segCuts':
                    val = C.js_json(v)
                elif isinstance(v, str):
                    val = v
                else:
                    val = C.js_number(v)
                say(f'rec {name} {mode} {k} {val}')
            say(f'recjson {name} {mode} {hashlib.sha256(C.js_json(rec).encode()).hexdigest()}')
    for name, text, _, _ in shards:
        rec = recs[name, 'off']
        data = text.encode()
        for k, (pk, res, _) in enumerate(C.frames(rec['stream'])):
            ch = data[k * C.CHUNK:(k + 1) * C.CHUNK]
            say(f'chunk {name} {k} {pk} {C.kernel_crystallize(ch)} {len(res)} '
                f'{hashlib.sha256(res.encode()).hexdigest()} {rec["leafHashes"][k]}')
        kr = C.grow(text, engrams=False, packets='kernel')
        say(f'kernel {name} {hashlib.sha256(kr["stream"].encode()).hexdigest()} {tf(kr["stream"] != rec["stream"])} '
            f'{tf(kr["chainId"] == rec["chainId"])} {tf(kr["merkleRoot"] == rec["merkleRoot"])}')
        br = C.grow(text, engrams=False, leaves='binary')
        say(f'binary {name} {br["leafHashes"][0]} {br["merkleRoot"]} {br["chainId"]} '
            f'{tf(all(a != b for a, b in zip(br["leafHashes"], rec["leafHashes"])))}')
    for name, text, _, _ in shards:
        rec = recs[name, 'off']
        q = C.exact_weave(rec['leafHashes'])
        n_ok, u_ok, s_ok = C.exact_weave_checks(rec['leafHashes'], rec['segCuts'], q)
        say(f'weave3 {name} {len(rec["leafHashes"])} ' + ' '.join(str(abs(c).bit_length()) for c in q) +
            f' {C.weave3_sha(q)} {tf(n_ok)} {tf(u_ok)} {tf(s_ok)}')
        cuts = rec['segCuts']
        for s, sw in enumerate(C.segment_weaves(rec['leafHashes'], cuts)):
            say(f'seg {name} {s} {cuts[s]} {cuts[s + 1]} {C.weave3_sha(sw)}')
    one = C.grow(b'Hello, world!', engrams=False)
    say('weave3full C1 ' + ' '.join(str(c) for c in C.exact_weave(one['leafHashes'])))
    for name, text, _, _ in shards:
        ids = WP.encode(text.encode(), v0)[0]
        say(f'ids {name} {len(ids)} {R.id_stream_sha(text.encode(), v0)} {lst(ids[:12])}')

    # ---- records
    lv = R.lvocab(v0)
    say(f'lvocab {lv}')
    say(f'lvocabHash {R.record_hash(lv)}')
    rows = R.addr_rows(TRACE_TOKENS, trace_words())
    for r in rows:
        say(f'addrrow {r}')
    root = R.addr_table_root(rows)
    la = R.laddr(v0.sha256, root)
    say(f'addrTableRoot {root}')
    say(f'laddr {la}')
    say(f'laddrHash {R.record_hash(la)}')
    lvh, lah = R.record_hash(lv), R.record_hash(la)
    lpreps = {}
    for j, (name, text, spdx, src) in enumerate(shards):
        for mode in ('off', 'on'):
            rec = recs[name, mode]
            f = R.lprep_fields(rec, text.encode(), v0, CORPUS, j, spdx, src, lvh, lah)
            s = R.lprep(f)
            lpreps[name, mode] = s
            say(f'lprep {name} {mode} {s}')
            say(f'lprepHash {name} {mode} {R.record_hash(s)}')
            salt = R.test_salt(j)
            say(f'lprepP {name} {mode} {salt} {R.lprep(f, R.TIER_P, salt)}')

    # ---- RFC 6962
    ct = [bytes.fromhex(h) for h in ('', '00', '10', '2021', '3031', '40414243', '5051525354555657',
                                     '606162636465666768696a6b6c6d6e6f')]
    log = M.Log(ct)
    for n in range(9):
        say(f'ct {n} {log.root(n).hex()}')
    L7 = M.Log(ct[:7])
    nm = {'a': L7.mth(0, 1), 'b': L7.mth(1, 2), 'c': L7.mth(2, 3), 'd': L7.mth(3, 4), 'e': L7.mth(4, 5),
          'f': L7.mth(5, 6), 'j': L7.mth(6, 7), 'g': L7.mth(0, 2), 'h': L7.mth(2, 4), 'i': L7.mth(4, 6),
          'k': L7.mth(0, 4), 'l': L7.mth(4, 7)}
    name_of = {v: k for k, v in nm.items()}
    for m in (0, 3, 4, 6):
        say(f'rfcpath {m} ' + ''.join(name_of.get(h, '?') for h in L7.path(m)))
    for m in (3, 4, 6):
        say(f'rfcproof {m} ' + ''.join(name_of.get(h, '?') for h in L7.consistency(m)))
    for j, K in enumerate(RFC_KS):
        D = M.synthetic_leaves(SEED_RFC + j, K)
        lg = M.Log(D)
        rt = lg.root()
        say(f'rfc {j} {K} {rt.hex()}')
        for i in range(K):
            p = lg.path(i)
            ok = M.verify_inclusion(i, K, M.leaf_hash(D[i]), p, rt)
            if K >= 2:
                o = (i + 1) % K
                wl = not M.verify_inclusion(i, K, M.leaf_hash(D[o]), p, rt)
                wp = not M.verify_inclusion(o, K, M.leaf_hash(D[i]), p, rt)
                say(f'incl {j} {i} {lst(h.hex() for h in p)} {tf(ok)} {tf(wl)} {tf(wp)}')
            else:
                say(f'incl {j} {i} {lst(h.hex() for h in p)} {tf(ok)} - -')
        for m in range(1, K + 1):
            p = lg.consistency(m)
            ok = M.verify_consistency(m, K, lg.root(m), rt, p)
            bad = bytearray(lg.root(m))
            bad[0] ^= 1
            say(f'cons {j} {m} {lst(h.hex() for h in p)} {tf(ok)} {tf(not M.verify_consistency(m, K, bytes(bad), rt, p))}')
        for i in range(K):
            rep = bytearray(D[i])
            rep[0] ^= 1
            say(f'alter {j} replace {i} {tf(M.root(M.tampered(D, "replace", i, bytes(rep))) != rt)}')
            say(f'alter {j} delete {i} {tf(M.root(M.tampered(D, "delete", i)) != rt)}')
            say(f'alter {j} insert {i} {tf(M.root(M.tampered(D, "insert", i, bytes(32))) != rt)}')
            if i + 1 < K:
                say(f'alter {j} swap {i} {tf(M.root(M.tampered(D, "swap", i)) != rt)}')
            if i >= 1:
                say(f'alter {j} truncate {i} {tf(M.root(M.tampered(D, "truncate", i)) != rt)}')
        say(f'alter {j} duplicate-last {K - 1} {tf(M.root(M.tampered(D, "duplicate-last")) != rt)}')
        hx = [d.hex() for d in D]
        a, b = M.merkle_shdccp2(hx), M.merkle_shdccp2(hx + [hx[-1]])
        say(f'shdccp2 {j} {K} {a} {b} {tf(a == b)}')
        vals = [int.from_bytes(d[:8], 'big') for d in D]
        say(f'xor {j} {K} {M.xor_summary(vals):016x}')
        q0 = C.chain_quaternion(vals)
        for i in range(K - 1):
            sw = list(vals)
            sw[i], sw[i + 1] = sw[i + 1], sw[i]
            say(f'swap {j} {i} {tf(M.xor_summary(sw) == M.xor_summary(vals))} {tf(C.chain_quaternion(sw) != q0)}')

    # ---- attestation
    ident = A.identity_id()
    kv = A.key_vector(ident, EPOCH)
    privs = {k: A.private_key(d) for k, d in A.TRACE_KEYS.items()}
    privs['C'] = A.private_key(int.from_bytes(hashlib.sha256(b'hyperbolic-lexicon trace key C').digest(), 'big')
                               % (A.P256_N - 1) + 1)
    say(f'identity {ident}')
    say(f'epoch {EPOCH}')
    say(f'keyVector {kv}')
    status = {'A': 'active', 'B': 'revoked'}
    entries = []
    for k in ('A', 'B'):
        jwk = A.jwk_of(privs[k].public_key())
        say(f'key {k} {A.key_id(jwk)} {jwk["x"]} {jwk["y"]} {status[k]}')
        entries.append({'publicJwk': jwk, 'keyVector': kv, 'status': status[k]})
    snap = A.snapshot_text(entries)
    say(f'registry {A.sha256hex(snap)} {snap}')
    session = V.Session(v0, lv, la, snap, A.sha256hex(snap))
    for which in ('r', 's'):
        n = 0
        while True:
            der = privs['A'].sign(f'hyperbolic-lexicon trace short {n}'.encode(), A.ECDSA_SHA256_DET)
            r_, s_ = A.decode_dss_signature(der)
            if (r_ if which == 'r' else s_) < 1 << 248:
                break
            n += 1
        say(f'short {which} {n} {der.hex()} {A.der_to_p1363(der).hex()} {A.der_to_p1363_unpadded(der).hex()}')

    def show(pkg_name, pkg):
        say(f'pkg {pkg_name} {hashlib.sha256(C.js_json(pkg).encode()).hexdigest()}')
        v = V.verify(pkg, session)
        say(f'verdict {pkg_name} {V.verdict_text(v)}')
        say(f'checks {pkg_name} ' + ''.join('P' if ok else '-' if ok is None else 'F' for _, ok, _ in v['checks']))

    def corpus(cid, mode, tier='S'):
        sh = [(recs[name, mode], text.encode()) for name, text, _, _ in shards]
        lps = []
        for j, (name, text, spdx, src) in enumerate(shards):
            f = R.lprep_fields(recs[name, mode], text.encode(), v0, cid, j, spdx, src, lvh, lah)
            lps.append(R.lprep(f, tier, R.test_salt(j) if tier == 'P' else None))
        lg_ = R.corpus_log(lps)
        lc = R.lcorpus(cid, lps, [s[2] for s in shards], lg_)
        lgs, cproof = R.grow_record(lps, cid, log=lg_)
        say(f'lcorpus {cid} {lc}')
        say(f'lgrow {cid} {lgs}')
        say(f'consproof {cid} {lst(h.hex() for h in cproof)}')
        pkgs = []
        for j in range(len(sh)):
            say(f'inclproof {cid} {j} {lst(h.hex() for h in lg_.path(j))}')
            block = A.attest(privs['A'], kv, lps[j], EPOCH)
            pkgs.append(V.make_package(sh[j][0], lps[j], block, lc, lg_.path(j), lgs, cproof,
                                       R.test_salt(j) if tier == 'P' else None))
        return pkgs

    def payload_of(block):
        return A.attestation_payload(block['keyId'], block['keyVector'], block['contentHash'], block['epochToken'])

    names = [s[0] for s in shards]
    pk = corpus(CORPUS, 'on')
    for j, p in enumerate(pk):
        b = p['attestation']
        der = A.p1363_to_der(bytes.fromhex(b['sig']))
        say(f'attest P{names[j]} {payload_of(b)} {b["sig"]} {der.hex()}')
        say(f'twin P{names[j]} {A.high_s_twin(bytes.fromhex(b["sig"])).hex()}')
        show(f'P{names[j]}', p)
    pkoff = corpus(CORPUS_OFF, 'off')
    for j, p in enumerate(pkoff):
        show(f'O{names[j]}', p)
    pkp = corpus(CORPUS_P, 'on', 'P')
    for j, p in enumerate(pkp):
        show(f'Q{names[j]}', p)

    # tampers on PS0 (synthetic) and PV0 (verb 00); T5 takes the next package's attestation, T6 the next salt
    for j in (0, 3):
        base, nm_ = pk[j], f'P{names[j]}'
        K = len(base['record']['leafHashes'])
        fl = V.silent_flips_of(base, 0, limit=1)
        t4 = V.t4_revoked(base, privs['B'], kv, EPOCH)
        say(f'attest {nm_}.T4 {payload_of(t4["attestation"])} {t4["attestation"]["sig"]} '
            f'{A.p1363_to_der(bytes.fromhex(t4["attestation"]["sig"])).hex()}')
        unknown = V.t4_revoked(base, privs['C'], kv, EPOCH)
        say(f'attest {nm_}.unknown {payload_of(unknown["attestation"])} {unknown["attestation"]["sig"]} '
            f'{A.p1363_to_der(bytes.fromhex(unknown["attestation"]["sig"])).hex()}')
        twin = V._copy(base)
        twin['attestation']['sig'] = A.high_s_twin(bytes.fromhex(base['attestation']['sig'])).hex()
        kvm = V._copy(base)
        kvm['attestation']['keyVector'] = V._last_digit(kvm['attestation']['keyVector'])
        sig_t = V._copy(base)
        sig_t['attestation']['sig'] = V._last_digit(sig_t['attestation']['sig'])
        eng = V._copy(base)
        eng['record']['engramCount'] += 1
        val = V._copy(base)
        val['record']['value'] = float(C.js_to_fixed(val['record']['value'] + 0.0001, 4))
        idx = V._copy(base)
        parts = idx['lprep'].split('|')
        parts[2] = str(int(parts[2]) + 1)
        idx['lprep'] = '|'.join(parts)
        inc = V._copy(base)
        inc['inclusion'][0] = V._last_digit(inc['inclusion'][0])
        con = V._copy(base)
        con['consistency'][-1] = V._last_digit(con['consistency'][-1])
        lcr = V._copy(base)
        lcr['lcorpus'] = '|'.join(p if i != 3 else V._last_digit(p) for i, p in enumerate(lcr['lcorpus'].split('|')))
        cases = [('T1', V.t1_strip(base)), ('T2', V.t2_crystal(base, 2, 0)), ('T3', V.t3_lprep(base)),
                 ('T4', t4), ('T5', V.t5_other(base, pk[j + 1])), ('T6', V.t6_salt(pkp[j], R.test_salt(j + 1))),
                 ('T7', V.t7_swap(base, 0)), ('T7last', V.t7_swap(base, K - 2)), ('T8', V.t8_chain_id(base)),
                 ('T9', V.t9_flip(base, 0, fl[0])), ('twin', twin), ('unknown', unknown), ('keyVector', kvm),
                 ('sig', sig_t), ('engramCount', eng), ('value', val), ('shardIndex', idx), ('inclusion', inc),
                 ('consistency', con), ('lcorpusRoot', lcr)]
        say(f'flip {nm_} 0 {fl[0]["i"]}:{fl[0]["bit"]}:{fl[0]["kind"]}')
        for cname, pkg in cases:
            show(f'{nm_}.{cname}', pkg)
    return '\n'.join(out) + '\n'


def main():
    check = '--check' in sys.argv[1:]
    if not W.available():
        print('skipped: no WordNet archive in the cache (run golden/make_wordnet_v1.cjs)', file=sys.stderr)
        return 2
    text = build(W.load())
    if check:
        same = os.path.exists(TRACE) and open(TRACE, 'rb').read() == text.encode('utf-8')
        print(('trace matches' if same else 'MISMATCH') + ': chain_v1.txt (%d lines, sha256 %s)' % (
            text.count('\n'), hashlib.sha256(text.encode()).hexdigest()[:16]), file=sys.stderr if not same else sys.stdout)
        return 0 if same else 1
    os.makedirs(os.path.dirname(TRACE), exist_ok=True)
    with open(TRACE, 'wb') as f:
        f.write(text.encode('utf-8'))
    print('wrote %s: %d lines, sha256 %s' % (os.path.relpath(TRACE, HERE), text.count('\n'),
                                              hashlib.sha256(text.encode()).hexdigest()))
    return 0


if __name__ == '__main__':
    sys.exit(main())
