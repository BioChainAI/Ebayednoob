#!/usr/bin/env python3
"""Hyperbolic Lexicon: the chain-track trace the browser core must reproduce line for line (Phase 3; L8-L10;
Amendment 7; the common rule "Authority").

    python3 -B "Pages/Hyperbolic Lexicon/reference/traces_chain.py"           write traces/chain_v1.txt
    python3 -B "Pages/Hyperbolic Lexicon/reference/traces_chain.py" --check   rebuild in memory and compare

What it holds (each line type is documented in the file's '#' header):
  - the codec on hand-made byte strings (packets, the kernel's normalisation, residuals, leaves, the float quaternion),
    V8's Math.hypot and Number.prototype.toFixed on doubles from Rng(8060);
  - Amendment 7 item 2's synthetic shards with seeds 8000 + i (i = 0, 1, 2) and the first two verb gloss shards
    (spike S4's cut, from the WordNet archive in the cache), each grown with engrams off and on: every record field,
    every chunk, the controls' growers (BioChain-AI's packet normalisation, leaves hashed over binary bytes), the exact
    weave and its segments, the V0 id stream;
  - the records: LVOCAB/1 (V0, the real one), a trace LADDR/1 over a 12-row table of fake tokens and words from
    Rng(8200 + r) (the real addrTableRoot needs map A over WordNet), LPREP/1 (Tier S and Tier P) of a fixed fake
    corpus 'lexicon-trace-v1', LCORPUS/1, LGROW/1;
  - RFC 6962: the Certificate Transparency vector and RFC 6962's worked proofs, then lists of K in (1, 2, 3, 4, 5, 7,
    8, 13) leaves from Rng(8100 + j): roots, every inclusion and consistency proof and their verdicts, every
    alteration, the shdccp/2 rule's duplicate-last collision and the XOR summary's blindness to swaps;
  - ATTEST/1 under two fixed test keys (A: RFC 6979 A.2.5's published key, active; B: derived from a label, revoked)
    with RFC 6979 deterministic ECDSA, so every signature is the same on every run; P1363 / DER vectors;
  - the hardened verifier's verdicts on clean packages and on hand-made tampers T1-T9 and more.
Seeds 8000 + i are reserved for traces; no claim uses them. Nothing here decides a claim, and no C0 shard is read.
--check exits 0 equal, 1 different, 2 skipped (no WordNet archive in the cache).
"""
