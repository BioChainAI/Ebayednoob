// Hyperbolic Lexicon: the pinned Unicode 15.1 table and V0 "lex0" as script files, so that a page reaches them
// without fetch and file:// works (PREREGISTRATION.md D5, L1; Amendment 4 item 1: Chromium loads the pinned data).
//
//   node "Pages/Hyperbolic Lexicon/reference/golden/make_js_data_v1.cjs"           write data/unicode_15_1_v1.js and
//                                                                                  data/vocab_v0_lex0.js
//   node "Pages/Hyperbolic Lexicon/reference/golden/make_js_data_v1.cjs" --check   rebuild in memory and compare the
//                                                                                  bytes (exit 0 equal, 1 different)
//
// Each output registers its file's exact text: in a page root.LexiconData = Object.assign(root.LexiconData || {},
// { <name>: text }); in Node module.exports = { <name>: text }. The source files are checked against their pins
// (unicode_15_1_v1.meta.json, vocab_v0.meta.json) before anything is written, and must be ASCII (both are): the
// outputs are then pure ASCII, so a page's charset cannot change them. lexicon_core.js verifies the text's SHA-256
// again when it reads it. Strings are written one chunk per line (one vocabulary entry per line for V0) so that a
// diff stays readable.
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const GOLDEN = __dirname;
const DATA = path.resolve(GOLDEN, '..', '..', 'data');
const OUTPUTS = [
    { name: 'unicode_15_1_v1', src: 'unicode_15_1_v1.json', meta: 'unicode_15_1_v1.meta.json', out: 'unicode_15_1_v1.js',
        what: 'the pinned Unicode 15.1 table (D5), exported by make_unicode_v1.py from CPython 3.13 unicodedata',
        licence: 'Unicode License v3 (reference/golden/LICENSE-UNICODE.txt)', lines: false },
    { name: 'vocab_v0_lex0', src: 'vocab_v0_lex0.txt', meta: 'vocab_v0.meta.json', out: 'vocab_v0_lex0.js',
        what: 'V0 "lex0", 8,192 entries, id = line number (D4; Amendment 1 item 3), trained by make_vocab_v0.py',
        licence: 'derived from WordNet 3.0 glosses (WordNet licence, reference/golden/LICENSE-WORDNET.txt)', lines: true },
];
const CHUNK = 100;

// a JS string literal for ASCII text: printable characters as they are, the rest escaped
function literal(s) {
    let out = '"';
    for (const ch of s) {
        const c = ch.charCodeAt(0);
        if (ch === '"' || ch === '\\') out += '\\' + ch;
        else if (c === 0x0A) out += '\\n';
        else if (c >= 0x20 && c <= 0x7E) out += ch;
        else out += '\\x' + c.toString(16).padStart(2, '0');
    }
    return out + '"';
}

function build(o) {
    const blob = fs.readFileSync(path.join(GOLDEN, o.src));
    const meta = JSON.parse(fs.readFileSync(path.join(GOLDEN, o.meta), 'utf8'));
    const digest = crypto.createHash('sha256').update(blob).digest('hex');
    if (digest !== meta.sha256 || blob.length !== meta.bytes) throw new Error(`${o.src}: sha256 ${digest} (${blob.length} B) is not the pinned ${meta.sha256} (${meta.bytes} B)`);
    for (const b of blob) if (b > 0x7F) throw new Error(`${o.src} is not ASCII`);
    const text = blob.toString('latin1');
    const chunks = [];
    if (o.lines) { let a = 0; for (let i = 0; i < text.length; i++) if (text[i] === '\n') { chunks.push(text.slice(a, i + 1)); a = i + 1; } if (a < text.length) chunks.push(text.slice(a)); }
    else for (let i = 0; i < text.length; i += CHUNK) chunks.push(text.slice(i, i + CHUNK));
    const out = [
        `// Hyperbolic Lexicon data: ${o.what}.`,
        `// Generated by reference/golden/make_js_data_v1.cjs from reference/golden/${o.src}; do not edit (--check compares).`,
        `// ${o.src}: ${blob.length} bytes, sha256 ${digest}. Licence: ${o.licence}.`,
        `// Registers the file's exact text as LexiconData.${o.name}; lexicon_core.js refuses it unless its SHA-256 is the pin.`,
        '(function (root, name, text) {',
        '    if (typeof module === \'object\' && module.exports) module.exports = { [name]: text };',
        '    else root.LexiconData = Object.assign(root.LexiconData || {}, { [name]: text });',
        `})(typeof self !== 'undefined' ? self : this, '${o.name}', [`,
        ...chunks.map(c => literal(c) + ','),
        '].join(\'\'));',
        '',
    ].join('\n');
    // the wrapper must give back the file's text exactly
    const m = { exports: {} };
    new Function('module', out)(m);
    if (m.exports[o.name] !== text) throw new Error(`${o.out}: the generated wrapper does not give back ${o.src}`);
    return Buffer.from(out, 'latin1');
}

function main() {
    const check = process.argv.includes('--check');
    let bad = 0;
    for (const o of OUTPUTS) {
        const want = build(o), p = path.join(DATA, o.out);
        if (check) {
            const same = fs.existsSync(p) && Buffer.compare(fs.readFileSync(p), want) === 0;
            if (!same) bad++;
            console.log(`${same ? 'ok  ' : 'MISMATCH'}  data/${o.out} (${want.length} B, sha256 ${crypto.createHash('sha256').update(want).digest('hex').slice(0, 16)}…)`);
        } else {
            fs.mkdirSync(DATA, { recursive: true });
            fs.writeFileSync(p, want);
            console.log(`wrote data/${o.out}: ${want.length} B, sha256 ${crypto.createHash('sha256').update(want).digest('hex')}`);
        }
    }
    if (check) console.log(bad ? `${bad} data file(s) differ from a rebuild` : 'data files match a rebuild');
    process.exit(bad ? 1 : 0);
}

if (require.main === module) main();
module.exports = { OUTPUTS, build };
